function makeInitialHistory(base: number, count = 28, spread = 0.4): number[] {
  const arr: number[] = [];
  for (let i = 0; i < count; i++) {
    arr.push(Number((base + Math.sin(i * 0.6) * spread).toFixed(2)));
  }
  return arr;
}

